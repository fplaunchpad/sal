def selfcheck():
    import os
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import embed_tree as ET
    import peritext_read_model as PRM
    from random import Random
    msgs = []
    ok = True

    # --- S1a directed: ins 1@0, 2@0, 3@1. Children of root: 2 newer than 1
    # so 2 first; 3 is 1's child so after 1. Hand-derived order: [2, 1, 3].
    E = ET.EmbedTree()
    s = E.init()
    for (i, a) in ((1, 0), (2, 0), (3, 1)):
        s = E.apply(s, ('ins', i, a))
    mine = PState()
    for (i, a) in ((1, 0), (2, 0), (3, 1)):
        mine.ins(i, chr(96 + i), a)
    ok1 = E.read(s) == [2, 1, 3] == mine.birth_order()
    ok &= ok1
    msgs.append(('S1a newest-first order (hand: [2,1,3])', ok1,
                 f'ET={E.read(s)} mine={mine.birth_order()}'))

    # --- S1b randomized sequential + delete: my live order vs ET refold.
    bad = 0
    for e in range(120):
        rng = Random(1000 + e)
        E2, s2, m2, ids = ET.EmbedTree(), ET.EmbedTree().init(), PState(), []
        nid = 1
        for _ in range(rng.randint(3, 14)):
            if ids and rng.random() < 0.3:
                x = rng.choice([i for i in ids if m2.live(i)] or ids)
                s2 = E2.apply(s2, ('del', x))
                m2.delete(x)
            else:
                a = rng.choice([0] + [i for i in ids if m2.live(i)])
                s2 = E2.apply(s2, ('ins', nid, a))
                m2.ins(nid, '?', a)
                ids.append(nid)
                nid += 1
        if E2.read(s2) != m2.live_order():
            bad += 1
    ok &= bad == 0
    msgs.append(('S1b 120 randomized histories vs embed_tree refold', bad == 0,
                 f'{bad} mismatches'))

    # --- S1c randomized merge: my union merge vs ET.merge (3-way, empty LCA).
    bad = 0
    for e in range(80):
        rng = Random(5000 + e)
        E3 = ET.EmbedTree()
        branches = [[E3.init(), PState()], [E3.init(), PState()]]
        nid = 1
        for br in branches:
            for _ in range(rng.randint(1, 6)):
                a = rng.choice([0] + list(br[1].shadow))
                br[0] = E3.apply(br[0], ('ins', nid, a))
                br[1].ins(nid, '?', a)
                nid += 1
        sM = E3.merge(E3.init(), E3.copy(branches[0][0]), E3.copy(branches[1][0]))
        mM = merge(branches[0][1], branches[1][1])
        if E3.read(sM) != mM.birth_order():
            bad += 1
    ok &= bad == 0
    msgs.append(('S1c 80 randomized 2-branch merges vs embed_tree.merge',
                 bad == 0, f'{bad} mismatches'))

    # --- S2a: PRM's own directed histories, expected literals restated from
    # peritext_read_model.py (hand-derived there). Build both models with the
    # same ids and compare BOTH to the literal AND to each other.
    def both(recs, marks_spec, dels_mid=(), post=(), dels_post=()):
        d = PRM.Doc()
        mm = PState()
        for (i, cp, a) in recs:
            d.ins(i, cp, a)
            mm.ins(i, cp, a)
        prm_marks = [PRM.make_mark(d, *spec[:5], startSide=spec[5],
                                   endSide=spec[6], op=spec[7]) for spec in marks_spec]
        for (mid, mt, val, s0, e0, ss, es, op) in marks_spec:
            mm.add_mark(Mark(mid, mt, op, s0, e0, ss, es, val))
        for x in dels_mid:
            d.delete(x)
            mm.delete(x)
        for (i, cp, a) in post:
            d.ins(i, cp, a)
            mm.ins(i, cp, a)
        for x in dels_post:
            d.delete(x)
            mm.delete(x)
        return d, prm_marks, mm

    cases = []
    # Ex1: bold [a,c], insert b within -> all bold.
    d, pm, mm = both([(1, 'a', 0), (2, 'c', 1)],
                     [(3, 'bold', None, 1, 2, 'before', 'after', 'add')],
                     post=[(4, 'b', 1)])
    cases.append(('Ex1', d, pm, mm, 'bold',
                  [('a', True), ('b', True), ('c', True)]))
    # Ex3: delete whole span, reinsert -> fresh text plain.
    d, pm, mm = both([(1, 'a', 0), (2, 'b', 1), (3, 'c', 2)],
                     [(10, 'bold', None, 1, 3, 'before', 'after', 'add')],
                     dels_mid=(1, 2, 3), post=[(4, 'd', 0)])
    cases.append(('Ex3', d, pm, mm, 'bold', [('d', False)]))
    # Ex7: typing at bold end extends (insert newer than mark).
    d, pm, mm = both([(1, 'a', 0), (2, 'b', 1)],
                     [(3, 'bold', None, 1, 2, 'before', 'after', 'add')],
                     post=[(4, 'x', 2)])
    cases.append(('Ex7', d, pm, mm, 'bold',
                  [('a', True), ('b', True), ('x', True)]))
    # Ex8 link half: endSide=before does not extend.
    d, pm, mm = both([(1, 'a', 0), (2, 'b', 1), (3, 'z', 2)],
                     [(4, 'link', 'u', 1, 3, 'before', 'before', 'add')],
                     post=[(5, 'x', 2)])
    cases.append(('Ex8', d, pm, mm, 'link',
                  [('a', True), ('b', True), ('x', False), ('z', False)]))
    # Trilemma re-span: delete separating C, newer D grabbed by growth.
    d, pm, mm = both([(1, 'A', 0), (2, 'B', 1), (3, 'C', 2)],
                     [(4, 'bold', None, 1, 2, 'before', 'after', 'add')],
                     post=[(5, 'D', 3)], dels_post=(3,))
    cases.append(('Trilemma', d, pm, mm, 'bold',
                  [('A', True), ('B', True), ('D', True)]))
    for name, d, pm, mm, mt, expected in cases:
        prm = PRM.render_flags(d, pm, PRM.DocumentOrderResolver(), mt)
        mineF = flags(mm, mt)
        good = prm == expected == mineF
        ok &= good
        msgs.append((f'S2a {name} (hand literal)', good,
                     f'prm={prm} mine={mineF} expected={expected}'))

    # --- S2b: 200 randomized histories, PRM render vs mine, exact.
    bad = 0
    first = None
    for e in range(200):
        rng = Random(9000 + e)
        d = PRM.Doc()
        mm = PState()
        pm = []
        nid = 1
        for cp in ('p', 'q'):
            d.ins(nid, cp, nid - 1)
            mm.ins(nid, cp, nid - 1)
            nid += 1
        for _ in range(rng.randint(4, 16)):
            live = [c for c in mm.live_order()]
            r = rng.random()
            if r < 0.40 or not live:
                a = rng.choice([0] + live)
                d.ins(nid, chr(97 + nid % 26), a)
                mm.ins(nid, chr(97 + nid % 26), a)
                nid += 1
            elif r < 0.60 and live:
                x = rng.choice(live)
                d.delete(x)
                mm.delete(x)
            else:
                birth = mm.birth_order()
                i = rng.randrange(len(birth))
                j = rng.randrange(i, len(birth))
                mt = rng.choice(['bold', 'italic'])
                op = 'add' if rng.random() < 0.7 else 'remove'
                ss = rng.choice(['before', 'after'])
                es = rng.choice(['after', 'before'])
                pm.append(PRM.make_mark(d, nid, mt, None, birth[i], birth[j],
                                        ss, es, op=op))
                mm.add_mark(Mark(nid, mt, op, birth[i], birth[j], ss, es, None))
                nid += 1
        prm = [(c, cp, frozenset(s)) for (c, cp, s)
               in PRM.render(d, pm, PRM.DocumentOrderResolver())]
        mineR = [(c, cp, s) for (c, cp, s) in render(mm)]
        if prm != mineR:
            bad += 1
            if first is None:
                first = (e, prm, mineR)
    ok &= bad == 0
    msgs.append(('S2b 200 randomized histories, PRM render vs mine',
                 bad == 0, f'{bad} mismatches' + (f' first={first}' if first else '')))
    return ok, msgs


