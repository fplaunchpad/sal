# Directed cases. Geometry D1 (the H-B countermodel family):
#   ins R=1 at root, L=2 at root (concurrent mints; L newer, reads first),
#   d=3 child of L. Reading order: L d R. Mark mid 5. Delete d. Cut.
# Continuations:
#   (a) beyond-cut ins n=10 anchored at L  (n newer than the mark)
#   (b) in-flight straggler ins n=4 anchored at L (n OLDER than the mark),
#       declared at the cut, delivered after compaction
#   (c) in-flight straggler ins n=4 anchored at d (lands right of d)
# Hand-derived expected covered sets (worked in whiteboard/marks-gc-note.md;
# twin birth orders: (a),(b) L n d R; (c) L d n R):
#   combo        mark                    (a) twin/early  (b) twin : early   (c) twin : early
#   start-inner  [s=d before, e=R after]   {R} = {R}      {R} : {R}          {n,R} : {R}    DIVERGES (c)
#   start-outer  [s=d after,  e=R after]   {R} = {R}      {R} : {n,R}        {n,R} : {n,R}  DIVERGES (b)
#   end-inner    [s=L before, e=d after]   {L,n} = {L,n}  {L,n} : {L}        {L} : {L}      DIVERGES (b)
#   end-outer    [s=L before, e=d before]  {L} = {L}      {L,n} : {L,n}      {L} : {L,n}    DIVERGES (c)
# Finding (a): with a beyond-cut NEWER insert the growth/skip rules
# compensate and ALL four combos agree; the task's directed candidate as
# narrated does not fire there. H-A must equal the twin in every cell.
# =========================================================================
D1_COMBOS = {
    'start-inner': dict(start_id=3, end_id=1, startSide='before', endSide='after'),
    'start-outer': dict(start_id=3, end_id=1, startSide='after', endSide='after'),
    'end-inner': dict(start_id=2, end_id=3, startSide='before', endSide='after'),
    'end-outer': dict(start_id=2, end_id=3, startSide='before', endSide='before'),
}
D1_EXPECT = {   # combo -> {variant: (twin covered cps, subjectB covered cps)}
    'start-inner': {'a': ('R', 'R'), 'b': ('R', 'R'), 'c': ('nR', 'R')},
    'start-outer': {'a': ('R', 'R'), 'b': ('R', 'nR'), 'c': ('nR', 'nR')},
    'end-inner': {'a': ('Ln', 'Ln'), 'b': ('Ln', 'L'), 'c': ('L', 'L')},
    'end-outer': {'a': ('L', 'L'), 'b': ('Ln', 'Ln'), 'c': ('L', 'Ln')},
}


def _d1_base(combo):
    st = PState()
    st.ins(1, 'R', 0)
    st.ins(2, 'L', 0)
    st.ins(3, 'd', 2)
    st.add_mark(Mark(5, 'bold', 'add', value=None, **D1_COMBOS[combo]))
    st.delete(3)
    return st


def _bold_cps(st):
    return ''.join(cp for cp, f in flags(st, 'bold') if f)


def d1_family():
    """Runs every (combo, variant) cell for attacks A and B against the twin.
    Returns list of (name, ok, detail)."""
    out = []
    for combo in D1_COMBOS:
        for variant in ('a', 'b', 'c'):
            barrier = _d1_base(combo)
            if variant == 'a':
                decl_ins = []
                pending = [(10, 'n', 2)]
            elif variant == 'b':
                decl_ins = [(4, 2)]
                pending = [(4, 'n', 2)]
            else:
                decl_ins = [(4, 3)]
                pending = [(4, 'n', 3)]
            exp_twin, exp_early = D1_EXPECT[combo][variant]
            twin = barrier.copy()
            for (i, cp, a) in pending:
                twin.ins(i, cp, a)
            got_twin = _bold_cps(twin)
            row_ok = got_twin == exp_twin
            det = [f'twin={got_twin!r} (hand: {exp_twin!r})']
            for attack, exp_subj in (('A', exp_twin), ('B', exp_early)):
                settled, keep, cmap, mo, _cs = build_cut(
                    barrier, attack, declared_ins=decl_ins)
                subj = apply_compaction(barrier, settled, keep, cmap, mo)
                for (i, cp, a) in pending:
                    subj.ins(i, cp, a)
                got = _bold_cps(subj)
                row_ok &= got == exp_subj
                if attack == 'A':
                    row_ok &= rview(subj) == rview(twin)
                det.append(f'{attack}={got!r} (hand: {exp_subj!r})')
            tag = 'agree' if exp_twin == exp_early else 'H-B DIVERGES'
            out.append((f'D1 {combo} variant {variant} [{tag}]',
                        row_ok, ' '.join(det)))
    return out


