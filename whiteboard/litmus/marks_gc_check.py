#!/usr/bin/env python3
"""
marks_gc_check -- task #110 phase 1: Python validation of two attacks on the
Peritext MARKS-layer GC problem (machine-checked verdicts, no Lean here).

Background. runtime/src/datatypes/peritext.js keeps text deletes LOGICAL
(shadow of every birth + a deleted set) because the document-order mark
resolver rehomes a DEAD boundary anchor to its nearest surviving neighbour in
reading order, which needs the dead anchor's birth position; consequently
compactStable REFUSES for peritext. This file tests two ways to remove that
refusal soundly, against a never-compacted twin as the specification.

H-A (retention roots): compact with keep-set = live ids UNION boundary anchor
    ids of present marks (dead anchors retained as dead records, re-coded).
    CLAIM: renderMarksDoc reads identical to the twin for EVERY beyond-cut
    continuation at every epoch. Sub-claims: A1 (retained coords keep order
    under the stable-prefix relabeling, machine-checked inside compact_map),
    A2 (dropped interior dead nodes are irrelevant to the resolver),
    A3 (add+remove pairs and their retention roots droppable under a guard).
    Cost claim: retained extra records <= 2 per mark record. Measured.

H-B (early re-anchoring): at the cut rewrite each dead mark boundary to the
    resolver's own cut-time rehoming target (side kept), then compact with NO
    mark retention. CLAIM (expected FALSE): reads identical to the twin.
    The weaker true statement (compacted replicas converge among themselves;
    divergence is only vs the uncompacted twin) is machine-checked separately
    and never presented as H-B succeeding.

Model notes (verified in selfcheck against embed_tree.py + peritext_read_model.py):
  * A coordinate is the tuple of birth-chain deltas (delta = id - anchor_id,
    ids are Lamport timestamps). Reading order = birth-chain lexicographic:
    ancestor before its subtree; among children of one anchor NEWER
    timestamps (larger deltas) sort FIRST. key() below realizes this.
  * The resolver is a transliteration of peritext_read_model.py's
    DocumentOrderResolver + render (the authoritative model); fidelity is
    cross-checked on the Ex1/3/5/7/8 + gravity + trilemma histories AND on
    randomized histories, implementation vs implementation.
  * Compaction is modeled abstractly (per the task): settled cut = a barrier
    state every replica has; drop settled-dead records outside the keep-set;
    order-preserving ordinal relabeling per sibling group with the in-flight
    freeze guard; beyond-cut mints re-derive coordinates from the (re-coded)
    anchor record, which IS the stable-prefix map's extension law H3.

PASS+FAIL convention (project rule): every claim carries a companion pinning
the tempting degenerate behavior; expected values in directed cases are
hand-derived in comments, never generated by running the model under test.
The twin comparison in the PBT uses the never-compacted twin as the spec,
which is not the implementation under test.

Run:  python3 marks_gc_check.py          # full (>=2000 trials per attack)
      python3 marks_gc_check.py --fast   # reduced trial counts (smoke)
"""
from __future__ import annotations
from dataclasses import dataclass, replace
import sys

# =========================================================================
# Coordinates and reading order.
# key(): negate deltas so ascending tuple sort gives (prefix first = ancestor
# before subtree, larger delta first = newer sibling first).
# =========================================================================
def key(coord):
    return tuple(-d for d in coord)


# =========================================================================
# The peritext state: text shadow (id -> coord, insert-only) + logical
# deleted set + codepoints + marks (grow-only map mid -> Mark).
# =========================================================================
@dataclass(frozen=True)
class Mark:
    mid: int                 # mark id = its Lamport timestamp (LWW + growth)
    mtype: str
    op: str                  # 'add' | 'remove'
    start_id: object         # char id, or ('sent', kind) after H-B rewriting
    end_id: object
    startSide: str = 'before'   # 'before' (inner) | 'after' (outer)
    endSide: str = 'after'      # 'after'  (inner) | 'before' (outer)
    value: object = None


class PState:
    __slots__ = ('shadow', 'anchor', 'deleted', 'codept', 'marks')

    def __init__(self):
        self.shadow = {}     # id -> coord tuple (birth constant within epoch)
        self.anchor = {}     # id -> anchor id at mint (0 = document start)
        self.deleted = set()
        self.codept = {}
        self.marks = {}      # mid -> Mark

    def copy(self):
        s = PState()
        s.shadow = dict(self.shadow)
        s.anchor = dict(self.anchor)
        s.deleted = set(self.deleted)
        s.codept = dict(self.codept)
        s.marks = dict(self.marks)
        return s

    def ins(self, i, cp, a):
        """Insert char i after anchor a (0 = doc start). Coord derived from
        THIS state's anchor record: on a compacted state this is exactly the
        stable-prefix map's extension law H3 (translate(pi ++ d) =
        translate(pi) ++ d)."""
        assert i > a, 'Lamport violation: op id must exceed anchor id'
        base = () if a == 0 else self.shadow[a]
        self.shadow[i] = base + (i - a,)
        self.anchor[i] = a
        self.codept[i] = cp

    def delete(self, i):
        self.deleted.add(i)

    def add_mark(self, m):
        self.marks[m.mid] = m

    def birth_order(self):
        return sorted(self.shadow, key=lambda i: key(self.shadow[i]))

    def live_order(self):
        return [c for c in self.birth_order() if c not in self.deleted]

    def live(self, c):
        return c in self.shadow and c not in self.deleted


def merge(x, y):
    """State union (all components grow-only; records are epoch-consistent).
    The coord-agreement assert is the cross-replica consistency check: it
    fires if the same event ever carries two coordinates in one epoch."""
    out = x.copy()
    for i, c in y.shadow.items():
        if i in out.shadow:
            assert out.shadow[i] == c, f'coord divergence at {i}: {out.shadow[i]} vs {c}'
        else:
            out.shadow[i] = c
            out.anchor[i] = y.anchor[i]
            out.codept[i] = y.codept[i]
    out.deleted |= y.deleted
    for mid, m in y.marks.items():
        if mid in out.marks:
            assert out.marks[mid] == m, f'mark divergence at {mid}'
        else:
            out.marks[mid] = m
    return out


# =========================================================================
# The document-order resolver, transliterated from peritext_read_model.py
# (DocumentOrderResolver._start_index/_end_index/covered + render). One
# addition: a mark anchor with NO record in the shadow (possible only in the
# no-retention negative control, or for H-B sentinels) degrades to the side's
# collapse branch -- the defined degenerate behavior whose read flips justify
# the runtime's current refusal.
# =========================================================================
def _scan(birth, deleted, i, step):
    j = i + step
    while 0 <= j < len(birth):
        if birth[j] not in deleted:
            return birth[j]
        j += step
    return None


def _start_index(st, m, live, pos, birth, bpos):
    n = len(live)
    a, side = m.start_id, m.startSide
    if isinstance(a, tuple):                       # H-B collapse sentinel
        return None if a[1] == 'collapse' else 0   # 'docstart'
    if not st.live(a):
        if a not in bpos:                          # dropped without retention
            return None if side == 'before' else 0
        a = _scan(birth, st.deleted, bpos[a], +1 if side == 'before' else -1)
        if a is None:
            return None if side == 'before' else 0
    i = pos[a]
    if side == 'before':                           # inner start: stable
        return i
    first = i + 1                                  # outer: skip newer run
    while first < n and live[first] > m.mid:
        first += 1
    return first


def _end_index(st, m, live, pos, birth, bpos):
    n = len(live)
    a, side = m.end_id, m.endSide
    if isinstance(a, tuple):
        return None if a[1] == 'collapse' else n - 1   # 'docend'
    if not st.live(a):
        if a not in bpos:
            return None if side == 'after' else n - 1
        a = _scan(birth, st.deleted, bpos[a], -1 if side == 'after' else +1)
        if a is None:
            return None if side == 'after' else n - 1
    i = pos[a]
    if side == 'after':                            # inner end: grows right
        last = i
        while last + 1 < n and live[last + 1] > m.mid:
            last += 1
        return last
    last = i - 1                                   # outer: step back newer run
    while last >= 0 and live[last] > m.mid:
        last -= 1
    return last


def render(st):
    """Per live char -> active (mtype, value) set; LWW per (char, mtype) by
    mid; 'remove' suppresses. Returns [(id, codepoint, frozenset)]."""
    birth = st.birth_order()
    live = [c for c in birth if c not in st.deleted]
    pos = {c: i for i, c in enumerate(live)}
    bpos = {c: i for i, c in enumerate(birth)}
    best = {c: {} for c in live}
    for m in st.marks.values():
        first = _start_index(st, m, live, pos, birth, bpos)
        last = _end_index(st, m, live, pos, birth, bpos)
        if first is None or last is None or first > last:
            continue
        for c in live[first:last + 1]:
            cur = best[c].get(m.mtype)
            if cur is None or m.mid > cur[0]:
                best[c][m.mtype] = (m.mid, m.op, m.value)
    return [(c, st.codept[c],
             frozenset((mt, v) for mt, (_i, op, v) in best[c].items() if op == 'add'))
            for c in live]


def rview(st):
    """Canonical render view for twin comparison."""
    return [(c, cp, tuple(sorted(s))) for (c, cp, s) in render(st)]


def flags(st, mtype):
    """[(codepoint, is-mtype)] projection, the paper's rendered view."""
    return [(cp, any(t == mtype for (t, _v) in s)) for (_c, cp, s) in render(st)]


# =========================================================================
# The abstract compactor.
#
# Settled cut = a barrier state every replica has (the PBT enforces this by
# a full exchange before each cut; the directed cases assert it by
# construction). Declared in-flight ops (stragglers minted before the cut,
# delivered after) are given as (id, anchor_id) for text and as Mark records
# for marks; their anchors are retained and the anchor's child sibling group
# is FROZEN (kept deltas verbatim) because the straggler's already-minted
# delta must keep its order against its siblings -- renumbering that group
# can flip an order (siblings with deltas 2 < 5(in flight) < 9 renumber to
# 1,2 and the frozen 5 jumps the ex-9), the same guard as runtime compact.js.
#
# compact_map: order-preserving relabeling of the kept coordinate tree.
# Machine-checks A1 inline: the comparator is preserved on every kept pair
# (retained-dead vs live, retained-dead vs retained-dead).
# =========================================================================
def compact_map(kept, frozen_parents, a1_pair_cap=45):
    """kept: {id: coord}. frozen_parents: set of parent coords whose child
    group must keep its deltas. Returns {id: new_coord}."""
    children = {}
    for c in kept.values():
        for k in range(len(c)):
            children.setdefault(c[:k], set()).add(c[k])
    newpfx = {(): ()}
    for p in sorted(children, key=len):     # parents strictly before children
        ds = sorted(children[p])
        renumber = p not in frozen_parents
        for idx, d in enumerate(ds):
            nd = (idx + 1) if renumber else d
            newpfx[p + (d,)] = newpfx[p] + (nd,)
    cmap = {i: newpfx[c] for i, c in kept.items()}
    # --- A1, machine-checked: comparator preserved on the kept set.
    ids = list(kept)
    if len(ids) <= a1_pair_cap:
        pairs = [(a, b) for x, a in enumerate(ids) for b in ids[x + 1:]]
    else:                                    # subsample on big states
        import random as _r
        rng = _r.Random(0xA1)
        pairs = [(rng.choice(ids), rng.choice(ids)) for _ in range(1200)]
        pairs = [(a, b) for a, b in pairs if a != b]
    for a, b in pairs:
        assert ((key(kept[a]) < key(kept[b])) == (key(cmap[a]) < key(cmap[b]))), \
            f'A1 violation: order of {a},{b} not preserved'
    return cmap


def rewrite_marks_early(barrier):
    """H-B: rewrite each DEAD mark boundary to the resolver's own cut-time
    rehoming target (nearest surviving neighbour on the side's scan
    direction, side kept; exhausted scan becomes the side's collapse
    sentinel). Computed once from the barrier, common to all replicas."""
    birth = barrier.birth_order()
    bpos = {c: i for i, c in enumerate(birth)}
    out = {}
    for m in barrier.marks.values():
        s, e = m.start_id, m.end_id
        if isinstance(s, int) and not barrier.live(s):
            t = _scan(birth, barrier.deleted, bpos[s],
                      +1 if m.startSide == 'before' else -1)
            s = t if t is not None else \
                ('sent', 'collapse' if m.startSide == 'before' else 'docstart')
        if isinstance(e, int) and not barrier.live(e):
            t = _scan(birth, barrier.deleted, bpos[e],
                      -1 if m.endSide == 'after' else +1)
            e = t if t is not None else \
                ('sent', 'collapse' if m.endSide == 'after' else 'docend')
        out[m.mid] = replace(m, start_id=s, end_id=e)
    return out


def a3_pairs(barrier, declared_mark_mids, guard=True):
    """A3: (add, remove) pairs droppable with their retention roots.
    A pair is (add m, remove r): same mtype, same boundaries AND sides,
    r.mid > m.mid. GUARDS (all required when guard=True):
      (i)   settledness: every concurrent mark is visible (the barrier is a
            settled cut) and none is declared in flight for this mtype;
      (iii) no OTHER same-mtype mark with mid < r.mid (else dropping r
            resurrects the older mark on any present or future overlap);
      (iv)  the growth-window guard (a finding of this file): no char id
            strictly between m.mid and r.mid exists among settled ids --
            such a char is grabbed by the add's growth but NOT the
            remove's, so the pair is not render-neutral. Future mints are
            Lamport-fresh (> r.mid), so checking the settled ids suffices.
    guard=False drops every syntactic pair (negative control)."""
    marks = list(barrier.marks.values())
    pairs = []
    for r in marks:
        if r.op != 'remove':
            continue
        for m in marks:
            if (m.op == 'add' and m.mtype == r.mtype and m.mid < r.mid
                    and m.start_id == r.start_id and m.end_id == r.end_id
                    and m.startSide == r.startSide and m.endSide == r.endSide):
                if guard:
                    others = [o for o in marks if o.mtype == r.mtype
                              and o.mid < r.mid and o.mid != m.mid]
                    if others:
                        continue                       # (iii)
                    if any(o.mtype == r.mtype and o.mid < r.mid
                           for o in declared_mark_mids):
                        continue                       # (i) in-flight mark
                    if any(m.mid < i < r.mid for i in barrier.shadow):
                        continue                       # (iv) growth window
                pairs.append((m, r))
    return pairs


def build_cut(barrier, attack, declared_ins=(), declared_marks=(),
              a3_guard=True):
    """Compute the cut artifacts from the (settled) barrier state.
    attack: 'A' retention roots | 'A3' A plus guarded pair-drop |
            'B' early re-anchoring, no mark retention |
            'NONE' no retention, no rewrite (negative control).
    Returns (settled, keep, cmap, marks_override, cutstats)."""
    settled = set(barrier.shadow)
    live = {i for i in settled if i not in barrier.deleted}
    infl_anchor = {a for (_i, a) in declared_ins if a != 0}
    for m in declared_marks:
        for a in (m.start_id, m.end_id):
            if isinstance(a, int):
                infl_anchor.add(a)
    infl_anchor &= settled
    marks = dict(barrier.marks)
    dropped_pairs = 0
    if attack == 'A3':
        for (am, rm) in a3_pairs(barrier, declared_marks, guard=a3_guard):
            if am.mid in marks and rm.mid in marks:
                del marks[am.mid]
                del marks[rm.mid]
                dropped_pairs += 1
    if attack == 'B':
        marks = rewrite_marks_early(barrier)
    if attack in ('A', 'A3'):
        mark_anchors = {a for m in marks.values()
                        for a in (m.start_id, m.end_id)
                        if isinstance(a, int)}
        for m in declared_marks:                     # straggler mark anchors
            for a in (m.start_id, m.end_id):
                if isinstance(a, int):
                    mark_anchors.add(a)
        mark_anchors &= settled
        keep = live | mark_anchors | infl_anchor
    else:                                            # 'B' | 'NONE'
        keep = live | infl_anchor
    frozen = set()
    for (_i, a) in declared_ins:
        if a == 0:
            frozen.add(())
        elif a in barrier.shadow:
            frozen.add(barrier.shadow[a])
    cmap = compact_map({i: barrier.shadow[i] for i in keep}, frozen)
    dead = settled - live
    cutstats = {
        'settled': len(settled), 'live': len(live), 'dead': len(dead),
        'dropped': len(dead - keep),
        'retained_dead': len(keep & dead),
        'retained_for_marks': len((keep & dead) - infl_anchor),
        'mark_records': len(marks),
        'dropped_pairs': dropped_pairs,
    }
    return settled, keep, cmap, marks, cutstats


def apply_compaction(st, settled, keep, cmap, marks_override):
    """One replica's state through the cut: drop settled-dead outside keep,
    re-code kept records, re-derive any unsettled record from its (already
    re-coded) anchor, restrict the deleted set, install the cut's marks."""
    out = PState()
    for i in sorted(st.shadow):                      # anchors before children
        if i in settled and i not in keep:
            continue
        if i in cmap:
            out.shadow[i] = cmap[i]
        else:                                        # unsettled own record
            a = st.anchor[i]
            assert a == 0 or a in out.shadow, \
                f'unsettled record {i} lost its anchor {a} (undeclared in-flight)'
            out.shadow[i] = (() if a == 0 else out.shadow[a]) + (i - a,)
        out.anchor[i] = st.anchor[i]
        out.codept[i] = st.codept[i]
    out.deleted = {i for i in st.deleted if i in out.shadow}
    out.marks = dict(marks_override)
    return out


