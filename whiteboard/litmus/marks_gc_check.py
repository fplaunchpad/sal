# SELFCHECK: fidelity of this file's model against the authoritative ones.
#   S1 reading order vs embed_tree.EmbedTree (fraction geometry): sequential
#      and randomized DAG (union merge here vs ET.merge there). This also
#      machine-verifies the task's order description: among children of one
